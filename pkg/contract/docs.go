// Dir is where the generated reference files live in the repository.
const Dir = "docs/reference"

// SchemaFile is the name of the JSON Schema of the report.
const SchemaFile = "factorymeter-v1.schema.json"

// SchemaID is the id the JSON Schema of the report carries.
const SchemaID = "https://raw.githubusercontent.com/marshal-org/factorymeter/main/" + Dir + "/" + SchemaFile

const generated = "<!-- Generated by \"factorymeter contract write " + Dir + "\". Do not edit by hand: change the definitions in pkg/line, pkg/record or pkg/contract and run it again. -->\n\n"

// Rules hold for every metric. They are stated once here instead of in each
// definition.
var Rules = []string{
	"A definition says \"the period\". For the value of a metric that is the whole window of the report, 13 weeks unless asked otherwise. For one point of its history it is one week.",
	"A station's numbers are counted when they happen, not when the change merges. A wait counts in the period it ended, and work in the period the item left the station. A change that waited four weeks for review and got it this week counts this week, at the review station, whether or not it has merged yet.",
	"The numbers about the whole line are measured over the changes merged in the period.",
	"Queue numbers are not measured over a period. They are the state at the end of it.",
	fmt.Sprintf("A median, a percentile or a share drawn from fewer than %d items is still reported, and marked thin. No trend is called on a thin value.", line.MinSample),
	"Every time is wall-clock time. Nights and weekends count, because the work waits through them.",
	"Changes by automation, such as dependency bumps and release bots, are reported as their own class and are left out of every number about the whole line.",
	"A metric id never changes meaning. When a definition has to change, the metric gets a new id and the old one stays or is removed in a new contract version.",
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ")
}

func code(list []string) string {
	out := make([]string, len(list))
	for i, s := range list {
		if s == "" {
			out[i] = "empty"
		} else {
			out[i] = "`" + s + "`"
		}
	}
	return strings.Join(out, ", ")
}

func betterWhen(g line.Good) string {
	switch g {
	case line.Up:
		return "higher"
	case line.Down:
		return "lower"
	}
	return "neither"
}

func minSample(m line.Metric) string {
	if m.MinSample == 0 {
		return "none"
	}
	return fmt.Sprint(m.MinSample)
}

func metricTable(b *strings.Builder, list []line.Metric) {
	b.WriteString("| Id | Name | Unit | Better when | Minimum sample | Cut by |\n|---|---|---|---|---|---|\n")
	for _, m := range list {
		fmt.Fprintf(b, "| `%s` | %s | `%s` | %s | %s | %s |\n", m.ID, cell(m.Name), m.Unit, betterWhen(m.Good), minSample(m), code(m.Slices))
	}
	b.WriteString("\n")
	for _, m := range list {
		fmt.Fprintf(b, "- `%s`: %s\n", m.ID, m.Definition)
	}
	b.WriteString("\n")
}

// MetricsMarkdown renders the metric registry as a reference page.
func MetricsMarkdown() string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# Metrics reference\n\n")
	fmt.Fprintf(&b, "Contract `%s`. %d metrics over %d stations and the line as a whole.\n\n", Version, len(line.Registry), len(line.Stations))
	b.WriteString("Every number factorymeter reports is listed here with its exact definition. The same list is in [`metrics.json`](metrics.json) for programs, and `factorymeter metrics` prints it.\n\n")

	b.WriteString("## The line\n\nWork passes through seven stations, in this order.\n\n| Station | Id | What moves through it | What happens there |\n|---|---|---|---|\n")
	for _, s := range line.Stations {
		fmt.Fprintf(&b, "| [%s](#%s) | `%s` | %s | %s |\n", s.Name, s.ID, s.ID, s.Item, cell(s.Does))
	}

	b.WriteString("\n## How to read a metric id\n\nAn id is `station.kind` or `station.kind.stat`, for example `review.wait.p50`: at the review station, the wait, the median. The station part is one of the seven station ids, or `line` for a number about the whole line.\n\nEvery station is asked the same questions, so a station is read the same way wherever it is.\n\n| Kind | What it answers |\n|---|---|\n")
	for _, k := range line.Kinds {
		fmt.Fprintf(&b, "| `%s` | %s |\n", k, cell(line.KindDoes[k]))
	}
	b.WriteString("\nA station that cannot observe one of them says why, and has no such metric. The stat part is `p50` for the median, `p90` for the 90th percentile, `oldest` for the age of the oldest item, `total` and `share` for the held hours.\n\n## Units\n\n| Unit | How to read it |\n|---|---|\n")
	for _, u := range line.Units {
		fmt.Fprintf(&b, "| `%s` | %s |\n", u, cell(line.UnitDoes[u]))
	}

	b.WriteString("\n## Rules that hold for every metric\n\n")
	for _, r := range Rules {
		fmt.Fprintf(&b, "- %s\n", r)
	}

	b.WriteString("\n## The constraint\n\nThe constraint is the station that holds work the longest. For each station that counts, factorymeter adds up the hours the items that left it in the period spent there, each item capped at the station's 90th percentile, and names the station with the largest share. It names none when fewer than ")
	fmt.Fprintf(&b, "%d changes merged in the period.\n\n", line.MinSample)

	for _, s := range line.Stations {
		fmt.Fprintf(&b, "## %s\n\n<a id=\"%s\"></a>%s\n\n", s.Name, s.ID, s.Does)
		fmt.Fprintf(&b, "- Item: %s.\n- Arrives: %s\n- Leaves: %s\n- Measured from: %s records.\n", s.Item, s.Arrives, s.Leaves, code(s.Needs))
		if s.InConstraint {
			b.WriteString("- Constraint: the station can be named the constraint.\n")
		} else {
			fmt.Fprintf(&b, "- Constraint: the station is never named the constraint. %s\n", s.Why)
		}
		kinds := make([]string, 0, len(s.NotObservable))
		for k := range s.NotObservable {
			kinds = append(kinds, string(k))
		}
		sort.Strings(kinds)
		for _, k := range kinds {
			fmt.Fprintf(&b, "- No `%s` number: %s\n", k, s.NotObservable[line.Kind(k)])
		}
		b.WriteString("\n")
		metricTable(&b, line.ForStation(s.ID))
	}
	b.WriteString("## The whole line\n\n<a id=\"line\"></a>Numbers about the line from end to end.\n\n")
	metricTable(&b, line.ForStation(line.Whole))
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// Catalog is the metric registry as a program reads it.
type Catalog struct {
	Schema   string         `json:"schema"`
	Kinds    []KindDoc      `json:"kinds"`
	Units    []UnitDoc      `json:"units"`
	Rules    []string       `json:"rules"`
	Stations []line.Station `json:"stations"`
	Metrics  []line.Metric  `json:"metrics"`
}

// KindDoc describes one kind of metric.
type KindDoc struct {
	ID   line.Kind `json:"id"`
	Does string    `json:"does"`
}

// UnitDoc describes one unit.
type UnitDoc struct {
	ID   line.Unit `json:"id"`
	Does string    `json:"does"`
}

// NewCatalog builds the catalog from the registry.
func NewCatalog() Catalog {
	c := Catalog{Schema: Version, Rules: Rules, Stations: line.Stations, Metrics: line.Registry}
	for _, k := range line.Kinds {
		c.Kinds = append(c.Kinds, KindDoc{k, line.KindDoes[k]})
	}
	for _, u := range line.Units {
		c.Units = append(c.Units, UnitDoc{u, line.UnitDoes[u]})
	}
	return c
}

// JSON writes v the way every generated file is written: indented, with a
// final newline and without escaping the characters HTML cares about.
func JSON(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func structTable(b *strings.Builder, t reflect.Type) {
	b.WriteString("| Field | Type | Meaning |\n|---|---|---|\n")
	for _, f := range fieldsOf(t) {
		doc := f.Doc
		if f.Enum != nil {
			doc += " One of " + code(f.Enum) + "."
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", f.Name, f.Type, cell(doc))
	}
	b.WriteString("\n")
}

// A Record is one kind of record of the store.
type Record struct {
	Kind  string
	Does  string
	Value any
}

// Records lists the record kinds in the order the docs print them.
var Records = []Record{
	{record.KindTicket, "An issue on GitHub, Linear or Jira. Tickets feed the spec station.", record.Ticket{}},
	{record.KindChange, "A pull request. Changes feed the code, review and merge stations, and tie CI runs and deploys to the line.", record.Change{}},
	{record.KindCIRun, "One attempt of one CI workflow on one commit. Runs on a commit of a change feed the ci station.", record.CIRun{}},
	{record.KindDeploy, "One deployment to an environment, or one published release. Deploys feed the verify and release stations.", record.Deploy{}},
	{record.KindLink, "A tie between two records: a change that closes a ticket, or a change that reverts another.", record.Link{}},
}

// RecordsMarkdown renders the record layout as a reference page.
func RecordsMarkdown() string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# Records reference\n\n")
	fmt.Fprintf(&b, "Record layout version %d.\n\n", record.SchemaVersion)
	b.WriteString("Records are what factorymeter keeps in its store. A source adapter turns what it reads from GitHub, Linear or Jira into these records and nothing else, and every metric is computed from them. So a new source needs no change to a metric.\n\n")
	b.WriteString("Every time is UTC. A time that has not happened is null, never a zero date. A record id is stable: syncing the same thing twice replaces the record.\n\n")
	b.WriteString("| Record | What it is |\n|---|---|\n")
	for _, r := range Records {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s |\n", r.Kind, r.Kind, cell(r.Does))
	}
	b.WriteString("\n")
	seen := map[reflect.Type]bool{}
	for _, r := range Records {
		for i, t := range structsOf(r.Value) {
			if seen[t] {
				continue
			}
			seen[t] = true
			if i == 0 {
				fmt.Fprintf(&b, "## %s\n\n<a id=\"%s\"></a>%s\n\n", t.Name(), r.Kind, r.Does)
			} else {
				fmt.Fprintf(&b, "### %s\n\n", t.Name())
			}
			structTable(&b, t)
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// ReportMarkdown renders the layout of the report as a reference page.
func ReportMarkdown() string {
	var b strings.Builder
	b.WriteString(generated)
	b.WriteString("# Report reference\n\n")
	fmt.Fprintf(&b, "Contract `%s`.\n\n", Version)
	b.WriteString("This is the layout of the JSON that `factorymeter report --format json` writes. The same layout is in [`" + SchemaFile + "`](" + SchemaFile + ") as a JSON Schema.\n\n")
	b.WriteString("Inside this version fields are only added. A reader must ignore a field it does not know. A field is never left out: a value that does not exist is null, an empty list or an empty string.\n\n")
	for i, t := range structsOf(Report{}) {
		if i == 0 {
			b.WriteString("## Report\n\n")
		} else {
			fmt.Fprintf(&b, "## %s\n\n", t.Name())
		}
		structTable(&b, t)
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// ReportSchema is the JSON Schema of the report.
func ReportSchema() map[string]any {
	return Schema(Report{}, SchemaID, "factorymeter report, version 1",
		"What factorymeter report writes as JSON. Inside this version fields are only added, so a reader must ignore a field it does not know.")
}

// Files builds every generated reference file, keyed by its name in Dir.
func Files() (map[string][]byte, error) {
	catalog, err := JSON(NewCatalog())
	if err != nil {
		return nil, err
	}
	schema, err := JSON(ReportSchema())
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"metrics.md":   []byte(MetricsMarkdown()),
		"metrics.json": catalog,
		"records.md":   []byte(RecordsMarkdown()),
		"report.md":    []byte(ReportMarkdown()),
		SchemaFile:     schema,
	}, nil
}
